"""Does the reliability ranking survive different choices? Writes docs/scorecard_sensitivity.md

    python analysis/scorecard_sensitivity.py

Re-scores the scorecard under alternative weightings and an alternative small-sample method
(Wilson lower bound instead of shrinkage), then reports how much the top of the list moves:
  - top-10 overlap with the baseline (out of 10)
  - Spearman rank correlation with the baseline (1.0 = identical order)
A robust scorecard keeps most of its top 10 under reasonable alternatives.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
MARTS = ROOT / "data" / "marts"

BASELINE = {"on_time": 0.40, "cancel": 0.20, "delay": 0.25, "controllable": 0.15}
SCENARIOS = {
    "Equal weights": {"on_time": 0.25, "cancel": 0.25, "delay": 0.25, "controllable": 0.25},
    "On-time heavy": {"on_time": 0.60, "cancel": 0.15, "delay": 0.15, "controllable": 0.10},
    "Cancellation heavy": {"on_time": 0.25, "cancel": 0.45, "delay": 0.20, "controllable": 0.10},
    "Ignore controllability": {"on_time": 0.45, "cancel": 0.25, "delay": 0.30, "controllable": 0.0},
    "Delay minutes heavy": {"on_time": 0.25, "cancel": 0.15, "delay": 0.50, "controllable": 0.10},
}


def load_scorecard() -> pd.DataFrame:
    parquet, csv = MARTS / "mart_reliability_scorecard.parquet", MARTS / "mart_reliability_scorecard.csv"
    return pd.read_parquet(parquet) if parquet.exists() else pd.read_csv(csv)


def zscore(series: pd.Series) -> pd.Series:
    sd = series.std(ddof=0)
    return (series - series.mean()) / sd if sd else series * 0


def score(df: pd.DataFrame, weights: dict, on_time_col: str = "adj_on_time_rate") -> pd.Series:
    return (
        weights["on_time"] * -zscore(df[on_time_col])
        + weights["cancel"] * zscore(df["adj_cancellation_rate"])
        + weights["delay"] * zscore(df["adj_avg_arr_delay_min"])
        + weights["controllable"] * zscore(df["adj_controllable_share"].fillna(df["adj_controllable_share"].mean()))
    )


def compare(df: pd.DataFrame, base: pd.Series, alt: pd.Series, top_n: int = 10) -> tuple[int, float]:
    top_base = set(df.index[base.rank(ascending=False, method="first") <= top_n])
    top_alt = set(df.index[alt.rank(ascending=False, method="first") <= top_n])
    rho = spearmanr(base, alt).statistic
    return len(top_base & top_alt), float(rho)


def main() -> None:
    df = load_scorecard().reset_index(drop=True)
    base = score(df, BASELINE)
    rows = []
    for name, weights in SCENARIOS.items():
        overlap, rho = compare(df, base, score(df, weights))
        rows.append((name, weights, overlap, rho))
    overlap, rho = compare(df, base, score(df, BASELINE, on_time_col="wilson_low_on_time_rate"))
    rows.append(("Wilson lower bound instead of shrinkage", BASELINE, overlap, rho))
    raw = df.assign(adj_on_time_rate=df["raw_on_time_rate"], adj_cancellation_rate=df["raw_cancellation_rate"],
                    adj_avg_arr_delay_min=df["raw_avg_arr_delay_min"], adj_controllable_share=df["raw_controllable_share"])
    overlap, rho = compare(df, base, score(raw, BASELINE))
    rows.append(("No small-sample adjustment (raw rates)", BASELINE, overlap, rho))

    lines = [
        "# Scorecard sensitivity check",
        "",
        f"{len(df):,} carrier-airport pairs ranked. Baseline weights: {BASELINE}. "
        "Generated by `analysis/scorecard_sensitivity.py` from `data/marts/mart_reliability_scorecard`.",
        "",
        "| Alternative | Top-10 overlap with baseline | Spearman rank correlation |",
        "|---|---:|---:|",
        *[f"| {name} | {ov}/10 | {r:.3f} |" for name, _, ov, r in rows],
        "",
        "How to read this: high overlap and correlation under the weight changes means the",
        "priority list does not depend on one arbitrary weighting. A big change when the",
        "small-sample adjustment is removed shows why the adjustment matters.",
    ]
    out = ROOT / "docs" / "scorecard_sensitivity.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
